import fs from "node:fs";
import path from "node:path";
import childhoodFile from "../../config/childhood-topics-v1.json";
import memoirFile from "../../config/memoir-topics-v3.json";

const RICKY_ID = "11111111-1111-4111-8111-111111111111";

function dollarQuote(value: string): string {
  const tag = value.includes("$eld$") ? "$eld2$" : "$eld$";
  return `${tag}${value}${tag}`;
}

function jsonb(value: unknown): string {
  return `${dollarQuote(JSON.stringify(value))}::jsonb`;
}

function text(value: string): string {
  return dollarQuote(value);
}

function transformMigration(source: string): string {
  let sql = source;
  sql = sql.replace(/create unique index /g, "create unique index if not exists ");
  sql = sql.replace(/create index /g, "create index if not exists ");
  sql = sql.replace(/create table /g, "create table if not exists ");
  sql = sql.replace(/create function /g, "create or replace function ");
  sql = sql.replace(
    /create trigger (\w+)([\s\S]*?)\bon (public\.\w+)/g,
    "drop trigger if exists $1 on $3;\ncreate trigger $1$2on $3",
  );
  sql = sql.replace(/create type (public\.(\w+)) as enum \(([\s\S]*?)\);/g, (_match, qualified: string, _name: string, values: string) => {
    return `do $type$\nbegin\n  create type ${qualified} as enum (${values});\nexception\n  when duplicate_object then null;\nend\n$type$;`;
  });
  sql = sql.replace(
    /alter table (public\.\w+)\s+add constraint (\w+)\s+([\s\S]*?);/g,
    (_match, table: string, name: string, rest: string) => {
      return `do $constraint$\nbegin\n  if not exists (select 1 from pg_constraint where conname = '${name}') then\n    alter table ${table}\n      add constraint ${name}\n      ${rest.trim()};\n  end if;\nend\n$constraint$;`;
    },
  );
  return sql.trim();
}

function seedSql(): string {
  const chapters = memoirFile.chapters
    .map((chapter, index) => {
      return `insert into public.chapters (id, title, optional, sort_order)
values (${text(chapter.id)}, ${jsonb({ en: chapter.en, zh: chapter.zh })}, ${chapter.optional}, ${index + 1})
on conflict (id) do update
  set title = excluded.title, optional = excluded.optional, sort_order = excluded.sort_order;`;
    })
    .join("\n\n");

  const rank = new Map(childhoodFile.recommend_order.map((id, index) => [id, index + 1]));
  const topics = childhoodFile.topics
    .map((topic) => {
      const recommendRank = rank.get(topic.id);
      return `insert into public.topics (
  id, chapter_id, config_version, title, opening_question, follow_ups,
  sensitive, recommend_by_default, recommend_rank
) values (
  ${text(topic.id)}, ${text(childhoodFile.chapter)}, ${text(childhoodFile.version)},
  ${jsonb({ en: topic.topic_en, zh: topic.topic_zh })},
  ${text(topic.opening_question)}, ${jsonb(topic.follow_ups)},
  ${topic.sensitive}, ${topic.recommend_by_default}, ${recommendRank ?? "null"}
)
on conflict (id) do update set
  chapter_id = excluded.chapter_id,
  config_version = excluded.config_version,
  title = excluded.title,
  opening_question = excluded.opening_question,
  follow_ups = excluded.follow_ups,
  sensitive = excluded.sensitive,
  recommend_by_default = excluded.recommend_by_default,
  recommend_rank = excluded.recommend_rank;`;
    })
    .join("\n\n");

  const states = childhoodFile.topics
    .map(
      (topic) => `insert into public.topic_states (user_id, topic_id)
values ('${RICKY_ID}', ${text(topic.id)})
on conflict (user_id, topic_id) do nothing;`,
    )
    .join("\n");

  return `-- Ricky, the ten chapters, and the twelve childhood topics. Same rows as pnpm db:seed.
insert into public.users (id, display_name, ui_locale, narration_locale, book_title)
values ('${RICKY_ID}', 'Ricky', 'en', 'en', 'Ricky''s story')
on conflict (id) do nothing;

${chapters}

${topics}

${states}`;
}

function main(): void {
  const migration = fs.readFileSync(
    path.join(process.cwd(), "supabase/migrations/20261111191446_init_schema.sql"),
    "utf8",
  );
  const body = `-- Idempotent schema and seed for a fresh hosted Postgres.
-- Apply with psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/schema.sql
-- Safe to run again. Generated by src/scripts/emit-schema.ts.

begin;

${transformMigration(migration)}

${seedSql()}

commit;
`;
  const out = path.join(process.cwd(), "db/schema.sql");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, body);
  console.log("wrote", out);
}

main();
